// Recipe 3 (Who Killed Santa?): every shipped case is generated and checked.
//   node tests/recipe3.mjs            check all cases, including the start table in js/cases3.js
//   node tests/recipe3.mjs --table    rebuild js/cases3.js by searching every case from scratch
//   node tests/recipe3.mjs --show     print a few cases

import { writeFileSync } from 'node:fs';
import { generatePuzzle3, truthOf, viewFor, countAll } from '../js/generator3.js';
import { logicalSolve, aloneOk } from '../js/solver.js';
import { clueHolds, clueText, withPresents, canStand } from '../js/clues.js';
import { OBJECTS, THEMES } from '../js/themes.js';
import { explainNext } from '../js/hints.js';

const theme = 'xmas';
const LIMIT = THEMES[theme].caseLimit;
const DESKS = ['easy', 'medium', 'hard'];
const strip = (t) => t.replace(/<[^>]+>/g, '');

if (process.argv.includes('--table')) {
  const table = {};
  for (const d of DESKS) table[d] = [...Array(LIMIT).keys()].map((i) => generatePuzzle3({ seed: i + 1, difficulty: d, theme, scan: true }).attempt);
  const body = `// Recipe 3 has a fixed list of cases per desk, so the attempt at which each one comes out can be
// written down: a phone then builds the case in one go instead of searching for it.
// Generated by \`node tests/recipe3.mjs --table\`; \`npm test\` checks it against a full search.
export const CASE_START = ${JSON.stringify({ [theme]: table })};
`;
  writeFileSync(new URL('../js/cases3.js', import.meta.url), body);
  console.log('wrote js/cases3.js', JSON.stringify(table));
  process.exit(0);
}

let fails = 0;
const fail = (...a) => { fails++; console.log('FAIL', ...a); };
const t0 = Date.now();
for (const d of DESKS) {
  const used = {}, shapes = {};
  let slow = 0, hintless = 0;
  for (let n = 1; n <= LIMIT; n++) {
    const tag = `${theme}-${d}-${n}`;
    const t = Date.now();
    const p = generatePuzzle3({ seed: n, difficulty: d, theme });
    slow = Math.max(slow, Date.now() - t);
    // the start table must give exactly what a search from scratch gives
    const scanned = generatePuzzle3({ seed: n, difficulty: d, theme, scan: true });
    if (JSON.stringify(scanned) !== JSON.stringify(p)) fail('start table', tag);
    if (JSON.stringify(generatePuzzle3({ seed: n, difficulty: d, theme })) !== JSON.stringify(p)) fail('not deterministic', tag);
    const sol = p.solution;
    const view = truthOf(p);
    const real = p.presents ? withPresents(view, p.presents.hidden) : view;
    for (const k in p.rating.used) used[k] = (used[k] || 0) + 1;
    shapes[p.shape] = (shapes[p.shape] || 0) + 1;

    // the scene
    if (!p.people[p.victim].santa || p.people[p.victim].name !== 'Santa') fail('victim is not Santa', tag);
    if (new Set(p.people.map((x) => x.initial)).size !== p.people.length) fail('initials clash', tag);
    if (!sol.every((i, k) => canStand(real, k, i))) fail('stand', tag);
    if (new Set(sol.map((i) => Math.floor(i / p.w))).size !== sol.length || new Set(sol.map((i) => i % p.w)).size !== sol.length) fail('lines', tag);
    if (!aloneOk(real, sol)) fail('alone', tag);

    // exactly one answer, and plain logic finds it
    if (countAll(view, 3) !== 1) fail('not unique', tag);
    const r = logicalSolve(view);
    if (!r.solved || r.order.some((o) => sol[o.person] !== o.cell)) fail('logic', tag);

    // the naughty list: nice statements are true, naughty ones false, the killer is on the list
    const naughty = new Set(p.naughty ? [...p.naughty.known, ...(p.naughty.hidden >= 0 ? [p.naughty.hidden] : [])] : []);
    const spoken = p.presents ? withPresents(p, p.presents.hidden) : p; // statements as they were said
    p.people.forEach((pr, k) => pr.clues.forEach((c) => {
      if (clueHolds(spoken, k, c, sol) === naughty.has(k)) fail(naughty.has(k) ? 'naughty statement is true' : 'nice statement is false', tag, strip(clueText(p, pr, c)));
    }));
    if (p.rules.list) {
      if (naughty.size !== 2 || !naughty.has(p.murderer) || naughty.has(p.victim)) fail('list', tag);
      if (!!p.rules.smudged !== (p.naughty.hidden >= 0)) fail('smudge', tag);
    } else if (p.naughty) fail('unexpected list', tag);
    if (p.naughty?.hidden >= 0) {
      if (p.impostor !== p.naughty.hidden) fail('impostor field', tag);
      for (let L = 0; L < p.people.length; L++) {
        if (L === p.victim || naughty.has(L)) continue;
        const wrong = viewFor(p, [...p.naughty.known, L]);
        if (!logicalSolve(wrong).contradiction || countAll(wrong, 1) !== 0) fail('wrong name survives', tag, p.people[L].name);
      }
    }

    // presents: three of them, toys hidden on the board, and the wrapping can be worked out
    if (p.rules.presents) {
      const g = p.presents;
      if (g.cells.length !== 3 || [...g.hidden].sort().join() !== g.kinds.join()) fail('presents', tag);
      if (p.cells.some((c) => c.obj && OBJECTS[c.obj].toy)) fail('a toy shows on the board', tag);
      if (!g.cells.every((i, j) => p.cells[i].obj === 'gift' && p.cells[i].gift === j)) fail('gift squares', tag);
      if (!r.presents.every((kinds, j) => kinds.length === 1 && kinds[0] === g.hidden[j])) fail('wrapping not worked out', tag);
    } else if (p.presents) fail('unexpected presents', tag);

    // hints: from an empty board and from every step along the way there is something to say
    const placed = new Array(p.people.length).fill(null);
    for (let step = 0; step < p.people.length; step++) {
      const h = explainNext(view, placed);
      if (!h || !h.steps.length || h.steps.some((x) => /undefined|NaN|\[object/.test(x))) { fail('hint', tag, step, h && h.steps); break; }
      if (step === 0 && h.steps.length < 2) hintless++;
      placed[h.target] = sol[h.target];
    }

    if (process.argv.includes('--show') && n <= 2) {
      console.log(`\n${tag} [${p.shape}] ${p.headline}  naughty=${JSON.stringify(p.naughty || null)} presents=${p.presents ? p.presents.hidden : null}`);
      p.people.forEach((pr, k) => console.log(`  ${pr.name}${pr.isVictim ? ' [V]' : ''}${k === p.murderer ? ' [K]' : ''}${naughty.has(k) ? ' [naughty]' : ''}: ${pr.clues.map((c) => strip(clueText(p, pr, c))).join(' ')}`));
      const h = explainNext(view, new Array(p.people.length).fill(null));
      console.log('  hint:', h.steps.join(' | '));
    }
  }
  console.log(`${theme} ${d}: ${LIMIT} cases · slowest ${slow}ms · ${JSON.stringify(used)} · ${JSON.stringify(shapes)}`);
}
console.log(fails ? `${fails} FAILURES` : `all ok in ${Date.now() - t0}ms`);
process.exit(fails ? 1 : 0);
